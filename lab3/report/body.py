def example_step_dda():
    s, dd = trace(R.step_by_step, *SEG), trace(R.dda, *SEG)
    rows = [["x", "y = kx + b (пошаговый)", "y (ЦДА, накопленное)", "пиксель"]]
    for (a, _), (c, _) in zip(s.rows, dd.rows):
        rows.append([a[1], a[2], c[2], a[3]])
    return rows


