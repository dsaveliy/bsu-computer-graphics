def castle_steps():
    t = trace(R.castle_pitteway, *SEG)
    notes = t.text().split("\n")[2:]          # первые две строки — о приведении к октанту
    out = []
    for n in notes:
        n = n.replace("m1", "<i>m</i><sub>1</sub>").replace("m2", "<i>m</i><sub>2</sub>")
        n = n.replace("ᴿ", "<sup>R</sup>").replace("^1", "<sup>1</sup>")
        out.append(f"– {n};")
    return out


